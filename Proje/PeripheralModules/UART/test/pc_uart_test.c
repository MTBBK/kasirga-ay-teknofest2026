int setup_uart(const char *device) {
    int fd = open(device, O_RDWR | O_NOCTTY | O_SYNC);

    if (fd < 0) {
        perror("open");
        exit(1);
    }

    struct termios tty;
    memset(&tty, 0, sizeof tty);

    if (tcgetattr(fd, &tty) != 0) {
        perror("tcgetattr");
        exit(1);
    }

// CRITICAL: Ensure settings match your FPGA UART configuration
    tty.c_cflag &= ~PARENB; // No parity
    tty.c_cflag &= ~CSTOPB; // 1 stop bit
    tty.c_cflag |= CS8;     // 8 bits
    cfsetispeed(&tty, B115200);
    cfsetospeed(&tty, B115200);

    tty.c_lflag = 0;
    tty.c_iflag = 0;
    tty.c_oflag = 0;

    tty.c_cc[VMIN]  = 0;
    tty.c_cc[VTIME] = 10;

    if (tcsetattr(fd, TCSANOW, &tty) != 0) {
        perror("tcsetattr");
        exit(1);
    }

    return fd;
}

int main() {
    int fd = setup_uart("/dev/ttyUSB1");

    char input[32];

    printf("AAAAAAAAAAAAAAAAAAAA: ");

    while (fgets(input, sizeof(input), stdin)) {
        if (input[0] == 'a') {
            int len = strlen(logo);

            printf("\nSending logo to Basys3...\n\n");

            for (int i = 0; i < len; i++) {
                write(fd, &logo[i], 1);

                char rx;
                int n = read(fd, &rx, 1);

                if (n > 0) {
                    putchar(rx);
                    fflush(stdout);
                }

                usleep(500); // small delay for UART stability
            }

            printf("\n\nDone.\n");
        } else {
            printf("Unknown command. Type a then Enter.\n");
        }

        printf("\nAAAAAAAAAAAAAAAAA: ");
    }

    close(fd);
    return 0;
}
